def ex_for(q):
    for k, v in EX.items():
        if k in q: return v
    return ''
def clean_text(s):
    s = re.sub(r'\s+', ' ', s).strip()
    s = re.sub(r'(\d)\*10(\d)\b', lambda m: m.group(1) + '·10' + '⁰¹²³⁴⁵⁶⁷⁸⁹'[int(m.group(2))], s)
    s = re.sub(r'(\d)◦', r'\1°', s).replace('◦', '°')
    s = s.replace(' ???', '').replace('???', '')
    return s
def build_items(src, subj, topic_fn):
    out = []
    for x in src:
        q = clean_text(x['q'])
        if any(d.strip() and d.strip() in q for d in DROP): continue
        opts = []
        for o in x['opts']:
            t = clean_text(o['t'])
            t = re.sub(r'\s+(?:10%|1|7 9 4|4 7)$', '', t) if not o['ok'] else t
            if t and t not in [p['t'] for p in opts]: opts.append({'t': t, 'ok': o['ok']})
        for k, v in FIX_KEY.items():
            if k in q:
                for p in opts: p['ok'] = (p['t'].replace(' ', '') == v)
        if sum(p['ok'] for p in opts) != 1 or len(opts) < 3: continue
        seed = int(hashlib.md5(q.encode()).hexdigest()[:8], 16)
        rnd = random.Random(seed); rnd.shuffle(opts)
        L = 'ABCDE'
        out.append({'topic': topic_fn(q), 'multi': False, 'correct': [L[i] for i, p in enumerate(opts) if p['ok']],
                    'q': q, 'opts': [{'l': L[i], 't': p['t']} for i, p in enumerate(opts)], 'ex': ex_for(q)})
    # қайталанатындарды алып тастау
    seen, res = set(), []
    for it in out:
        k = re.sub(r'\W', '', it['q'].lower())[:70]
        if k in seen: continue
        seen.add(k); res.append(it)
    return res
def tgo_topic(q):
    if re.search(r'мәтін|Сөйлем|сөзді|сөзбен|стил|тақырып|синоним|Өлеңді', q, re.I) or len(q) > 300: return 'Сыни ойлау: мәтінмен жұмыс'
    if re.search(r'%|пайыз', q): return 'Пайыз'
    if re.search(r'жас|жылдан', q): return 'Мәтін есеп: жас'
    if re.search(r'км|жылдамдық|шақырым|сағ', q): return 'Мәтін есеп: қозғалыс, жұмыс'
    if re.search(r'≤|<|>|теңсіздік|теңдеу', q): return 'Теңдеу, теңсіздік'
    if re.search(r'шаршы|үшбұрыш|шеңбер|квадрат|бұрыш|аудан|куб|призма|көлем', q, re.I): return 'Геометрия'
    return 'Сандар және логика'
def eng_topic(q):
    ql = q.lower()
    if re.search(r'\bif\b|wish', ql): return 'Grammar: conditionals, wish'
    if re.search(r'\b(a|an|the)\b\s*[_…]|article', ql): return 'Grammar: articles'
    if re.search(r'must|can|may|should|could|have to|ought', ql): return 'Grammar: modal verbs'
    return 'Grammar: tenses and verb forms'
tgo = build_items(T, 'fundamentals', tgo_topic)
eng = build_items(E, 'english', eng_topic)
