files = []
def emit(items, subj, per, start, title):
    chunks = [items[i:i + per] for i in range(0, len(items), per)]
    if len(chunks) > 1 and len(chunks[-1]) < per // 2: chunks[-2] += chunks.pop()
    for j, qs in enumerate(chunks):
        v = start + j; key = 'v%d-%s' % (v, subj)
        st = {'key': key, 'variant': v, 'subject': subj, 'lang': 'kz', 'origLang': 'en' if subj == 'english' else 'kz', 'source': 'col',
              'title': 'Нұсқа %d · %s' % (v, title), 'questions': [dict({'id': key + '-' + str(i + 1), 'n': i + 1}, **x) for i, x in enumerate(qs)]}
        open(os.path.join(ROOT, 'data/sets', key + '.js'), 'w', encoding='utf-8').write('Shyn.addSet(' + json.dumps(st, ensure_ascii=False) + ');\n')
        files.append(key)
